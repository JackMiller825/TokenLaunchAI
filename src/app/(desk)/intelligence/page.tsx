"use client";

import { Gate, PageIntro } from "@/components/desk";

export default function IntelligencePage() {
  return (
    <Gate>
      {(data) => (
        <div>
          <PageIntro
            eyebrow="Understanding"
            title="Token intelligence"
            text={`Generated by ${data.intelligence?.generator || "no report yet"}. Audience notes describe fit, not proven demand.`}
          />
          {!data.intelligence ? (
            <p className="text-muted">Run a website analysis to create this report.</p>
          ) : (
            <div className="grid gap-4 lg:grid-cols-2">
              {data.intelligence.content.sections.map((section) => (
                <article key={section.id} className="panel p-5">
                  <h2 className="text-lg text-white">{section.title}</h2>
                  <p className="mt-2 text-sm leading-6 text-muted">{section.body}</p>
                </article>
              ))}
              <article className="panel p-5 lg:col-span-2">
                <h2 className="text-lg text-white">Audience categories</h2>
                <div className="mt-3 grid gap-3 md:grid-cols-2">
                  {data.intelligence.content.audiences.map((audience) => (
                    <div key={audience.name} className="rounded-xl border border-border p-3">
                      <h3 className="text-white">{audience.name}</h3>
                      <p className="mt-1 text-sm text-muted">{audience.why}</p>
                      <p className="mt-2 text-xs text-teal">Evidence: {audience.evidence}</p>
                    </div>
                  ))}
                </div>
              </article>
            </div>
          )}
        </div>
      )}
    </Gate>
  );
}
